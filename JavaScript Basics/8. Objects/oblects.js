// Objects store key-value pairs.

// Object declaration
let person = {
    name: "Shivam",
    age: 21,
    city: "New Delhi"
};

// Print statements
console.log("Name:", person.name); // Output: Shivam
console.log("Age:", person.age);   // Output: 21
console.log("City:", person.city); // Output: New Delhi
